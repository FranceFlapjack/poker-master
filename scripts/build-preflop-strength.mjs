#!/usr/bin/env node
// Generate js/engine/preflop-strength.js — each of the 169 starting hands' equity against one random
// hand, all five board cards to come.
//
// This is COMPUTED, not quoted: it is our own equityMC over a fixed seed, so the file is reproducible
// and the provenance is "this app measured it". Regenerate with:
//
//   node scripts/build-preflop-strength.mjs
//
// It is a table rather than a live computation because the bots need a number instantly for every
// preflop decision, and 169 values never change.

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { GRID, idx, cellName, cellCombos, newRange } from '../js/engine/ranges.js'
import { equityMC } from '../js/engine/equity.js'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const TRIALS = 9000
const MAX_OPP = 8
const t0 = Date.now()

// One row per opponent count, because equity against ONE random hand is the wrong question at a full
// table and using it as if it were the right one makes a bot call with everything. Aces are 85% against
// one opponent and closer to 39% against eight; a median hand is around 50% and around 11%.
const table = []
const any = newRange().fill(1)

for (let opp = 1; opp <= MAX_OPP; opp++) {
  const row = new Array(169).fill(0)
  const villains = Array.from({ length: opp }, () => any)
  for (let i = 0; i < GRID; i++) {
    for (let j = 0; j < GRID; j++) {
      const hand = cellCombos(i, j)[0]    // one representative combo; suits are symmetric preflop
      const r = equityMC([hand, ...villains], [], [], { trials: TRIALS, seed: 1000 + opp * 211 + idx(i, j) })
      row[idx(i, j)] = Math.round(r.equity[0] * 10000) / 10000
    }
  }
  table.push(row)
  process.stdout.write(`  ${opp} opponent${opp === 1 ? ' ' : 's'}: done\n`)
}
const values = table[0]

const ranked = [...values.keys()].sort((a, b) => values[b] - values[a])
const best = ranked.slice(0, 5).map(k => `${cellName(Math.floor(k / GRID), k % GRID)} ${(values[k] * 100).toFixed(1)}%`)
const worst = ranked.slice(-3).map(k => `${cellName(Math.floor(k / GRID), k % GRID)} ${(values[k] * 100).toFixed(1)}%`)

const rowsFor = row => {
  const out = []
  for (let i = 0; i < GRID; i++) out.push('    ' + Array.from({ length: GRID }, (_, j) => row[idx(i, j)].toFixed(4)).join(', ') + ',')
  return out.join('\n')
}
const body = table.map((row, k) => `  // ${k + 1} opponent${k ? 's' : ''}\n  new Float32Array([\n${rowsFor(row)}\n  ]),`).join('\n')

writeFileSync(join(ROOT, 'js/engine/preflop-strength.js'), `// GENERATED by scripts/build-preflop-strength.mjs — do not edit by hand.
//
// Each of the 169 starting hands' equity against 1..${MAX_OPP} uniformly random hands, all five board
// cards to come. Measured by this app's own equityMC at ${TRIALS.toLocaleString()} trials per cell per
// opponent count with a fixed seed, so the file reproduces exactly. Nothing here is quoted.
//
// There is a row per opponent count because ONE row is actively misleading. Aces are about 85% against
// a single random hand and about 39% against eight; a median hand goes from roughly half to roughly a
// tenth. A bot that reads the one-opponent number at a nine-handed table concludes that almost every
// hand is worth a call, which is exactly what happened before this file had rows.
//
// What it still is NOT: a ranking to play by. Random hands are not a real range, and this takes no
// account of position or of what anybody's betting says. It is a cheap strength signal for the bots.
//
// Heads-up, top: ${best.join(', ')}
// Heads-up, bottom: ${worst.join(', ')}

const TABLE = [
${body}
]

/**
 * Equity for a grid cell against \`opponents\` random hands, 0..1.
 * Counts above ${MAX_OPP} clamp to ${MAX_OPP} — a ten-handed table is not a case this app deals.
 */
export function preflopStrength(i, j, opponents = 1) {
  const row = TABLE[Math.max(1, Math.min(${MAX_OPP}, opponents)) - 1]
  return row[i * ${GRID} + j]
}

export const PREFLOP_EQUITY = TABLE[0]
`)

console.log(`wrote js/engine/preflop-strength.js in ${((Date.now() - t0) / 1000).toFixed(1)}s`)
console.log('top:   ', best.join('  '))
console.log('bottom:', worst.join('  '))
