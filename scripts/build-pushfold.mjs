#!/usr/bin/env node
// Generate content/charts/pushfold-hu.json — heads-up shove-or-fold equilibrium at 1..20 big blinds.
//
//   node scripts/build-pushfold.mjs [trials]
//
// Two stages. First a 169x169 preflop equity matrix, measured by this app's own equityMC; only the
// upper triangle is sampled, since equity(a,b) + equity(b,a) = 1 and a hand against itself is 0.5 by
// symmetry. Then nashPushFold solves each stack depth against that matrix.
//
// This runs offline because the matrix takes minutes and never changes. What ships is the solved chart,
// not the matrix — the app has no need for 14,000 matchups at runtime.

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { GRID, idx, cellName, newRange, serializeRange } from '../js/engine/ranges.js'
import { equityMC } from '../js/engine/equity.js'
import { nashPushFold, widthOf } from '../js/engine/pushfold.js'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const TRIALS = Number(process.argv[2]) || 3000
const DEPTHS = Array.from({ length: 20 }, (_, i) => i + 1)
const t0 = Date.now()

// --- stage 1: the matrix ----------------------------------------------------
const M = new Float64Array(169 * 169)
const single = c => { const r = newRange(); r[c] = 1; return r }
const ranges = Array.from({ length: 169 }, (_, c) => single(c))

let done = 0
const pairs = (169 * 168) / 2
for (let a = 0; a < 169; a++) {
  M[a * 169 + a] = 0.5                       // a hand against itself splits, by symmetry
  for (let b = a + 1; b < 169; b++) {
    const r = equityMC([ranges[a], ranges[b]], [], [], { trials: TRIALS, seed: 7 + a * 271 + b })
    M[a * 169 + b] = r.equity[0]
    M[b * 169 + a] = 1 - r.equity[0]          // the other side is the complement, ties included
    if (++done % 2000 === 0) {
      process.stdout.write(`  matrix ${done}/${pairs} (${((Date.now() - t0) / 1000).toFixed(0)}s)\n`)
    }
  }
}
const equity = (a, b) => M[a * 169 + b]
console.log(`  matrix done in ${((Date.now() - t0) / 1000).toFixed(0)}s`)

// sanity: the matrix must be antisymmetric, and aces must beat everything
let worstSym = 0
for (let a = 0; a < 169; a++) for (let b = 0; b < 169; b++) worstSym = Math.max(worstSym, Math.abs(M[a * 169 + b] + M[b * 169 + a] - 1))
const AA = idx(0, 0)
const aaBeatsAll = Array.from({ length: 169 }, (_, c) => c === AA || M[AA * 169 + c] > 0.5).every(Boolean)
console.log(`  antisymmetry error ${worstSym.toExponential(1)}; aces beat every other hand: ${aaBeatsAll}`)
if (!aaBeatsAll) { console.log('  ABORT: the matrix is wrong'); process.exit(1) }

// --- stage 2: solve each depth ---------------------------------------------
//
// MIXED CELLS are shipped alongside the pure ranges, and that is not a detail. The solver returns
// frequencies; a chart needs a decision, so cells above 0.5 are written in and the rest out. But a hand
// the equilibrium plays 48% of the time is not a fold, and a trainer that marks you wrong for shoving it
// would be inventing a certainty the solve does not have. So the band around a half is recorded
// separately and the trainer refuses to score it.
const MIXED_LO = 0.35, MIXED_HI = 0.65
const mixedRange = freq => {
  const r = newRange()
  for (let c = 0; c < 169; c++) r[c] = (freq[c] >= MIXED_LO && freq[c] <= MIXED_HI) ? 1 : 0
  return r
}
const countCells = r => { let n = 0; for (let c = 0; c < 169; c++) if (r[c]) n++; return n }

const depths = []
for (const S of DEPTHS) {
  const r = nashPushFold({ effStack: S, equity })
  const pushMixed = mixedRange(r.pushFreq), callMixed = mixedRange(r.callFreq)
  depths.push({
    bb: S,
    push: serializeRange(r.push),
    call: serializeRange(r.call),
    pushPct: Math.round(r.pushPct * 1000) / 10,
    callPct: Math.round(r.callPct * 1000) / 10,
    pushMixed: serializeRange(pushMixed),
    callMixed: serializeRange(callMixed),
    exploitability: Math.round(r.exploitability * 1e5) / 1e5,
    converged: r.converged,
  })
  const mix = countCells(pushMixed) + countCells(callMixed)
  console.log(`  ${String(S).padStart(2)}bb  push ${(100 * r.pushPct).toFixed(1).padStart(5)}%  call ${(100 * r.callPct).toFixed(1).padStart(5)}%  ${String(mix).padStart(2)} mixed  ${r.converged ? 'converged' : 'NOT CONVERGED'}`)
}

writeFileSync(join(ROOT, 'content/charts/pushfold-hu.json'), JSON.stringify({
  id: 'pushfold-hu',
  title: 'Push or fold, heads-up',
  subtitle: 'Small blind shoves or folds; big blind calls or folds',
  stackDepth: '1–20 big blinds',
  provenance: {
    kind: 'computed-by-this-app',
    isSolverOutput: true,
    source: 'js/engine/pushfold.js — iterated best response (fictitious play) over js/engine/equity.js, generated by scripts/build-pushfold.mjs',
    isGTO: true,
    basis: `Solved, not authored. When both players are short enough that the only sensible actions are shove or fold, the game is small enough to solve exactly: 169 hands each side and no streets afterwards. Equity came from a 169x169 matrix measured at ${TRIALS.toLocaleString()} trials per matchup.`,
    note: 'HEADS-UP and CHIP EV only. Multiway push/fold is a different game and is not solved here. At a final table the money is not the chips — see the ICM lab — and there the CALLING range is clearly too wide: every caller is risking chips worth more to them than the pot is paying. The shoving side is not so simple, because tighter callers fold more often and that pushes the other way; this app has not solved ICM push/fold and will not guess at the size of that adjustment. Past about 15 big blinds shoving stops being the right model at all; those rows are included for completeness, not as advice.',
    copied: 'Nothing is copied. This is the output of this repository solving the game itself, which is why it is the one chart here that may fairly be called an equilibrium.',
    accuracy: `Each depth is solved to within ${depths[0] ? depths[0].exploitability : '0.005'} big blinds of exploitability, a bound chosen to sit under the sampling error of the equity matrix rather than below it.`,
    mixed: `Some hands are MIXED: the solve leaves them between ${MIXED_LO} and ${MIXED_HI}, meaning the equilibrium plays them some of the time and folds them the rest. They are listed separately rather than rounded into the range, because a hand played half the time is a coin flip and marking either answer wrong would invent a certainty the solve does not have.`,
  },
  depths,
}, null, 2) + '\n')

console.log(`\nwrote content/charts/pushfold-hu.json in ${((Date.now() - t0) / 1000).toFixed(0)}s`)
